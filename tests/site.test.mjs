import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { html, root, read, loadAtlas } from './helpers/load.mjs';

test('index.html carries a Content-Security-Policy with no inline-script allowance', () => {
  const m = html.match(/<meta http-equiv="Content-Security-Policy" content="([^"]+)"/);
  assert.ok(m, 'CSP meta tag missing');
  const scriptSrc = m[1].split(';').map(s => s.trim()).find(s => s.startsWith('script-src'));
  assert.equal(scriptSrc, "script-src 'self'");
  assert.ok(/object-src 'none'/.test(m[1]) && /base-uri 'none'/.test(m[1]));
});

test('no inline scripts or inline event handlers in index.html', () => {
  assert.deepEqual([...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>/g)].map(x => x[0]), []);
  assert.deepEqual([...html.matchAll(/\son[a-z]+\s*=/gi)].map(x => x[0]), []);
});

test('no inline event handlers or javascript: URLs are generated by app.js', () => {
  const js = read('assets/app.js');
  assert.deepEqual([...js.matchAll(/\son(click|change|input|submit|load|error)\s*=\s*\\?["']/gi)].map(x => x[0]), []);
  assert.ok(!/javascript:/i.test(js));
  assert.ok(!/\beval\s*\(|new Function\(/.test(js));
});

test('every script and stylesheet referenced by index.html exists and is local', () => {
  for (const m of html.matchAll(/(?:src|href)="([^"#]+\.(?:js|css))"/g)) {
    assert.ok(!/^https?:/.test(m[1]), `external asset ${m[1]}`);
    assert.ok(fs.existsSync(path.join(root, m[1])), `${m[1]} missing`);
  }
});

test('search.js and verification.js load before app.js', () => {
  const order = [...html.matchAll(/<script src="([^"]+)"/g)].map(m => m[1]);
  const app = order.indexOf('assets/app.js');
  assert.ok(order.indexOf('data/verification.js') > -1 && order.indexOf('data/verification.js') < app);
  assert.ok(order.indexOf('assets/search.js') > -1 && order.indexOf('assets/search.js') < app);
});

test('external links open safely', () => {
  const js = read('assets/app.js') + html;
  for (const m of js.matchAll(/target="_blank"([^>]*)>/g)) assert.ok(/rel="noopener/.test(m[1]) || /rel='noopener/.test(m[1]), `target=_blank without rel=noopener: ${m[0].slice(0, 80)}`);
});

test('GitHub Pages deploy is gated on the test suite', () => {
  const y = read('.github/workflows/pages.yml');
  assert.ok(/npm test/.test(y) && /npm run check/.test(y), 'pages.yml validate job must run check and tests');
});

test('scripts/check.mjs passes on the repository', () => {
  const r = spawnSync(process.execPath, ['scripts/check.mjs'], { cwd: root, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
});

test('scripts/check.mjs fails when a verification record is broken (the gate is not vacuous)', () => {
  const tmp = fs.mkdtempSync(path.join(fs.realpathSync(process.env.TMPDIR || '/tmp'), 'atlas-'));
  for (const d of ['assets', 'data', 'scripts']) fs.cpSync(path.join(root, d), path.join(tmp, d), { recursive: true });
  fs.copyFileSync(path.join(root, 'index.html'), path.join(tmp, 'index.html'));
  const f = path.join(tmp, 'data/verification.js');
  fs.writeFileSync(f, fs.readFileSync(f, 'utf8').replace("lastVerified: '2026-11-20', status: 'GA (v1.0)'", "lastVerified: 'yesterday', status: 'GA (v1.0)'"));
  const r = spawnSync(process.execPath, ['scripts/check.mjs'], { cwd: tmp, encoding: 'utf8' });
  fs.rmSync(tmp, { recursive: true, force: true });
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /lastVerified must be YYYY-MM-DD/);
});

test('service matrix entries link to existing service pages', () => {
  const A = loadAtlas(); const ids = new Set(A.services.map(s => s.id));
  for (const m of A.serviceMatrix.comparisonMatrix) assert.ok(ids.has(m.atlasId || m.id), m.id);
});
